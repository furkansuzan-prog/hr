"""Generate reference docs from code (single source of truth): KPI catalog, data dictionary, permission matrix.
python scripts/gen_docs.py ../docs
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.analytics.calculators import CALCULATORS  # noqa: E402
from app.analytics.catalog import KPI_CATALOG  # noqa: E402
from app.models import Base  # noqa: E402
from app.security.catalog import HEALTH_DERIVED_KPIS, PERMISSIONS, ROLE_TEMPLATES  # noqa: E402

out = Path(sys.argv[1] if len(sys.argv) > 1 else "../docs")
HDR = "<!-- GENERATED by backend/scripts/gen_docs.py - do not edit by hand -->\n\n"

# ---------------------------------------------------------------- KPI catalog
lines = [HDR, "# KPI Kataloğu / KPI Catalogue\n\n",
         f"{len(KPI_CATALOG)} tanım; {sum(1 for k in KPI_CATALOG if k['status'] == 'active')} aktif ve doğrulanmış. "
         "`draft` tanımlar üretimde hesaplanamaz (ADR-008). Standart referansları **gösterge niteliğinde eşleştirmedir, uyum iddiası değildir.**\n\n",
         "Ortak kurallar: payda 0 → `not_computable` (asla 0); kaynak veri yok → `insufficient_data`; "
         "kişi sayısı < `HRSWI_MIN_GROUP_SIZE` (5) → `suppressed`; her sonuç formül versiyonu, pay/payda, örneklem, "
         "veri kalite puanı ve veri kökeni (lineage) taşır.\n\n",
         "| Kod | Ad (TR) | Name (EN) | Birim | Yön | Durum | Hesaplayıcı | Standart (gösterge) |\n|---|---|---|---|---|---|---|---|\n"]
for k in KPI_CATALOG:
    calc = k["formula"]["calculator_key"]
    impl = calc if calc in CALCULATORS else "—"
    lines.append(f"| {k['code']} | {k['name']['tr']} | {k['name']['en']} | {k['unit']} | {k['direction']} | "
                 f"{k['status']}{' · cost' if k['sensitive'] else ''} | `{impl}` | {', '.join(k['standard_refs']) or '—'} |\n")
lines.append("\n## Aktif KPI ayrıntıları\n")
for k in KPI_CATALOG:
    if k["status"] != "active":
        continue
    f = k["formula"]
    lines.append(f"\n### {k['code']} — {k['name']['tr']} / {k['name']['en']} / {k['name']['ru']}\n\n"
                 f"- **Formül:** {f['formula_text']}\n- **Pay:** {f['numerator_def']}\n- **Payda:** {f['denominator_def']}\n"
                 f"- **Amaç:** {k['purpose']}\n- **Dahil:** {k['inclusion_rules']}\n- **Hariç:** {k['exclusion_rules']}\n"
                 f"- **Veri kaynakları:** {', '.join(k['data_sources'])} · **Veri sahibi:** {k['data_owner_role']}\n"
                 f"- **Sıklık / kapsam:** {k['frequency']} · {', '.join(k['scope_levels'])}\n"
                 f"- **Eşikler (hedef/uyarı/kritik):** {k['target_value']} / {k['warning_threshold']} / {k['critical_threshold']}"
                 f"{' (yıllıklaştırılmış değere uygulanır)' if f['parameters'].get('annualize') else ''}\n"
                 f"- **Parametreler (v1):** `{f['parameters']}`\n- **Eksik veri:** {k['missing_data_behavior']}\n")
(out / "KPI_CATALOG.md").write_text("".join(lines))

# ---------------------------------------------------------------- data dictionary
dd = [HDR, "# Veri Sözlüğü / Data Dictionary\n\n",
      f"{len(Base.metadata.tables)} tablo. Şema kaynağı: `backend/app/models/*` → Alembic migration'ları.\n\n"]
for name in sorted(Base.metadata.tables):
    t = Base.metadata.tables[name]
    doc = ""
    for m in Base.registry.mappers:
        if m.local_table is t and m.class_.__doc__:
            doc = " ".join(m.class_.__doc__.split())
    dd.append(f"\n## `{name}`\n\n{doc}\n\n| Kolon | Tip | Null | Anahtar / FK |\n|---|---|---|---|\n")
    for c in t.columns:
        keys = []
        if c.primary_key:
            keys.append("PK")
        keys += [f"→ {fk.target_fullname}" for fk in c.foreign_keys]
        if c.index:
            keys.append("idx")
        dd.append(f"| {c.name} | {c.type} | {'✓' if c.nullable else ''} | {' '.join(keys)} |\n")
    cons = [str(getattr(x, 'name', '')) for x in t.constraints if x.__class__.__name__ in ("UniqueConstraint", "CheckConstraint")]
    if cons:
        dd.append(f"\nKısıtlar: {', '.join(c for c in cons if c and c != 'None')}\n")
(out / "DATA_DICTIONARY.md").write_text("".join(dd))

# ---------------------------------------------------------------- permission matrix
roles = list(ROLE_TEMPLATES)
pm = [HDR, "# Yetki Matrisi / Permission Matrix\n\n",
      "Roller veri olarak saklanır ve tenant bazında yapılandırılabilir; aşağıdaki başlangıç şablonlarıdır. "
      "Her rol ataması `tenant` veya `legal_entity` kapsamında yapılır (ADR-005).\n\n",
      "- **Firma bazlı (D-9, ADR-025):** `HRSWI_FEATURE_SUBCONTRACTORS=false` (varsayılan) iken `legal_entity` kapsamı "
      "yalnızca o firmadır; sözleşme ilişkisi (alt yüklenici) üzerinden genişleme yalnızca bayrak açıkken.\n"
      "- **`health.read` (D-12, ADR-025):** sağlık kaynaklı KPI'lar (" + ", ".join(sorted(HEALTH_DERIVED_KPIS))
      + ") `kpi.read` ∩ `health.read` kapsamıyla görünür; `health.read` olmayan okuyucu KPI-003 kırılımında raporlu / "
      "iş kazası / korunan izin saatlerini göremez. Proje / departman yöneticileri, operasyon, üst yönetim, finans, "
      "denetçi ve yüklenici yöneticisi şablonlarında **yoktur** (PO-5).\n\n",
      "| İzin | " + " | ".join(r.replace("_", " ").title() for r in roles) + " |\n",
      "|---|" + "---|" * len(roles) + "\n"]
for p, desc in PERMISSIONS.items():
    pm.append(f"| `{p}` — {desc} | " + " | ".join("●" if p in ROLE_TEMPLATES[r][1] else "" for r in roles) + " |\n")
(out / "PERMISSION_MATRIX.md").write_text("".join(pm))
print("generated:", [p.name for p in out.glob("*.md")])
