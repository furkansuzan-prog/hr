"""Generate the HR-manager target-setting form (docs/KPI_TARGETS_REQUEST.md) from the catalog + live demo values.
python scripts/kpi_targets_form.py ../docs/KPI_TARGETS_REQUEST.md
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from sqlalchemy import select  # noqa: E402

from app.analytics import engine  # noqa: E402
from app.analytics.dashboards import default_period  # noqa: E402
from app.core.db import SessionLocal  # noqa: E402
from app.models import KpiDefinition, Tenant  # noqa: E402
from app.security.access import AccessContext  # noqa: E402


def fmt(v):
    return "—" if v is None else (f"{float(v):,.2f}".rstrip("0").rstrip("."))


out = Path(sys.argv[1] if len(sys.argv) > 1 else "../docs/KPI_TARGETS_REQUEST.md")
with SessionLocal() as db:
    tid = db.execute(select(Tenant.id).where(Tenant.code == "DEMO")).scalar_one()
    ctx = AccessContext(user_id=None, tenant_id=tid, email="system:form", locale="tr",
                        grants={"kpi.read": None, "cost.read": None})
    ps, pe = default_period()
    defs = db.execute(select(KpiDefinition).where(KpiDefinition.status == "active").order_by(KpiDefinition.code)).scalars()
    rows = []
    for d in defs:
        try:
            r = engine.evaluate(db, ctx, d.code, ps, pe)
            val = fmt(r["annualized_value"] if r["annualized_value"] is not None else r["value"]) if r["status"] == "ok" \
                else r["status"]
        except engine.KpiError as e:
            val = f"({e})"
        yon = {"lower_better": "↓ düşük iyi", "higher_better": "↑ yüksek iyi"}.get(d.direction, "nötr")
        rows.append(f"| {d.code} | {d.name['tr']} | {d.unit} | {yon} | {fmt(d.target_value)} / {fmt(d.warning_threshold)} / "
                    f"{fmt(d.critical_threshold)} | {val} | | | | |")
lines = [
    "<!-- GENERATED by backend/scripts/kpi_targets_form.py -->\n\n",
    "# KPI Hedef ve Eşik Belirleme Formu — İK Yöneticisi\n\n",
    "**Amaç:** Aktif KPI'ların kurum hedeflerini ve uyarı/kritik eşiklerini belirlemek. Eşikler panellerdeki "
    "renkli durum göstergesini (iyi / uyarı / kritik) yönetir; boş bırakılan KPI'da gösterge çıkmaz.\n\n",
    "**Nasıl doldurulur**\n",
    "- *Hedef*: ulaşılmak istenen değer. *Uyarı* ve *Kritik*: göstergenin sarıya / kırmızıya döndüğü sınırlar.\n",
    "- Yönü kontrol edin (↓ düşük iyi / ↑ yüksek iyi). Yanlışsa *Yön* sütununa doğrusunu yazın.\n",
    "- \"Yıllık\" işaretli oran KPI'larında (devir, eğitim saati) eşikler **yıllıklaştırılmış** değere uygulanır.\n",
    "- *Demo değer* sentetik veriden hesaplanmıştır (son 12 tam ay); yalnızca ölçek fikri verir, hedef için "
    "kullanılmamalıdır. Kendi geçmiş verinizi yükledikten sonra form yeniden üretilebilir.\n",
    "- KPI-003 (devamsızlık) kurum tanımıyla güncellendi: habersiz devamsızlık, raporlu gün, yıllık izin, ücretsiz izin, "
    "diğer izinler. Doğum/ebeveyn izninin dahil edilip edilmeyeceğini *Not* sütununda belirtin.\n\n",
    f"Dönem: {ps} – {pe}\n\n",
    "| Kod | KPI | Birim | Yön | Mevcut hedef / uyarı / kritik | Demo değer | **Hedef** | **Uyarı** | **Kritik** | **Not / Yön** |\n",
    "|---|---|---|---|---|---|---|---|---|---|\n",
    *[r + "\n" for r in rows],
    "\nDoldurulan değerler sisteme `kpi_definitions` eşik alanları olarak girilir (katalog güncellemesi + "
    "`python -m app.seed.reference --apply`). Formül değişmediği için yeni formül versiyonu oluşmaz.\n",
]
out.write_text("".join(lines))
print(f"written {out} ({len(rows)} KPIs)")
